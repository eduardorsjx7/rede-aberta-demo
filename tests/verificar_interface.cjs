const { chromium } = require('playwright');
const fs = require('fs');
const assert = require('assert/strict');
const base = require('path').resolve(__dirname, '..');
(async () => {
  const config = JSON.parse(fs.readFileSync(process.env.REDE_ABERTA_CONFIG || `${base}/dados/app.json`));
  const url = `http://127.0.0.1:${config.porta}`;
  const browser = await chromium.launch({headless:true});
  const ctx = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await ctx.newPage();
  const erros = [];
  page.on('pageerror', e => erros.push(e.message));
  await page.goto(`${url}/#sessao=${config.token}`);
  await page.waitForFunction(() => !document.querySelector('#mensagem').textContent.includes('Conectando'));
  const inicial = await page.evaluate(async () => await fetch('/api/estado').then(r=>r.json()));
  assert.ok(!inicial.ativo && !inicial.limpeza_pendente, 'Encerre a atividade ou use um servidor de teste isolado.');
  assert.equal(await page.locator('#iniciar').isEnabled(), true);
  if (process.env.VERIFICAR_WIFI === '1') {
    await page.getByRole('button', {name:'Verificar equipamento'}).click();
    await page.waitForFunction(() => document.querySelector('#mensagem').textContent.includes('Equipamento pronto'));
    assert.notEqual(await page.locator('#interface').inputValue(), '');
  }
  await page.getByRole('button', {name:'Iniciar ensaio', exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#status-rede').textContent === 'Ensaio ativo');
  await page.getByRole('button', {name:'Simular aparelho', exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#observados').textContent === '1');
  await page.getByRole('button', {name:'Simular envio', exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#envios').textContent === '1');
  const popupPromise = page.waitForEvent('popup');
  await page.locator('#abrir-telao').click();
  const telao = await popupPromise;
  telao.on('pageerror', e => erros.push(e.message));
  await telao.waitForFunction(() => document.querySelector('#modo-telao').textContent.includes('DADOS FICTÍCIOS'));
  await telao.setViewportSize({width:1280,height:720});
  await page.locator('#revelar').click();
  await page.locator('#confirmacao button[value="cancelar"]').click();
  assert.equal(await telao.locator('#dados-telao').isHidden(), true);
  await page.locator('#revelar').click();
  await page.locator('#confirmacao button[value="confirmar"]').click();
  await telao.waitForFunction(() => !document.querySelector('#dados-telao').hidden);
  assert.match(await telao.locator('#registros').innerText(), /Visitante 1/);
  await telao.screenshot({path:'/tmp/rede-aberta-resultados.png'});
  await page.locator('#proximo').click();
  await telao.waitForFunction(() => document.querySelector('#passo-telao').textContent === '2 / 7');
  assert.equal(await telao.locator('#dados-telao').isHidden(), true);
  assert.equal(await telao.locator('#registros').innerText(), '');
  for(let i=0; i<7; i++) {
    await page.getByRole('button', {name:new RegExp(`^Etapa ${i+1}:`)}).click();
    await telao.waitForFunction((n) => document.querySelector('#passo-telao').textContent === `${n+1} / 7`, i);
    const medidas = await telao.evaluate(() => {
      const palco = document.querySelector('#palco');
      const corpo = document.querySelector('#corpo-telao').getBoundingClientRect();
      const rodape = document.querySelector('.slide-footer').getBoundingClientRect();
      return {largura:palco.clientWidth, altura:palco.clientHeight, fim:corpo.bottom, rodape:rodape.top};
    });
    assert.equal(medidas.largura/medidas.altura,16/9);
    assert.ok(medidas.fim <= medidas.rodape, `Slide ${i+1} sobrepõe rodapé: ${JSON.stringify(medidas)}`);
    if(i===1) await telao.screenshot({path:'/tmp/rede-aberta-telao.png'});
  }
  // O laboratório usa conexões reais mesmo dentro de um ensaio do roteiro.
  await page.locator('#preparar-comparacao').click();
  await page.waitForFunction(() => document.querySelector('#status-comparacao').textContent.includes('Pronta no notebook'));
  await page.locator('#enviar-notebook').click();
  await page.locator('#confirmacao button[value="cancelar"]').click();
  assert.equal(await page.locator('#total-comparacao').textContent(), '0 envios nesta comparação');
  await page.locator('#enviar-notebook').click();
  await page.locator('#confirmacao button[value="confirmar"]').click();
  await page.waitForFunction(() => document.querySelector('#total-comparacao').textContent === '2 envios nesta comparação');
  assert.match(await page.locator('#resultados-comparacao').innerText(), /Texto encontrado nos bytes/);
  assert.match(await page.locator('#resultados-comparacao').innerText(), /TLSv1\.[23]/);
  const formPromise = page.waitForEvent('popup');
  await page.locator('#url-comparacao-http').click();
  const formulario = await formPromise;
  await formulario.waitForLoadState();
  assert.equal(new URL(formulario.url()).hostname, 'localhost');
  assert.ok(!(await ctx.cookies(formulario.url())).some(cookie => cookie.name === 'rede_sessao'), 'O formulário não deve receber o cookie do painel.');
  await formulario.locator('#mensagem').fill('OLA_TURMA');
  await formulario.locator('input[name="concordo"]').check();
  await formulario.getByRole('button', {name:'Enviar por HTTP', exact:true}).click();
  await formulario.getByRole('status').waitFor();
  await page.waitForFunction(() => document.querySelector('#total-comparacao').textContent === '3 envios nesta comparação');
  await page.locator('#projetar-comparacao').click();
  await page.locator('#confirmacao button[value="confirmar"]').click();
  await telao.waitForFunction(() => !document.querySelector('#comparacao-telao').hidden);
  assert.match(await telao.locator('#modo-telao').innerText(), /COMPARAÇÃO REAL/);
  assert.match(await telao.locator('#quadros-telao').innerText(), /OLA_TURMA/);
  await telao.screenshot({path:'/tmp/rede-aberta-https.png'});
  assert.ok(await telao.evaluate(() => document.querySelector('.conclusao-comparacao').getBoundingClientRect().bottom < document.querySelector('.slide-footer').getBoundingClientRect().top));
  await page.getByRole('button', {name:/^Etapa 1:/}).click();
  await telao.waitForFunction(() => document.querySelector('#comparacao-telao').hidden);
  assert.equal(await telao.locator('#quadros-telao').innerText(), '');
  await page.locator('#encerrar-comparacao').click();
  await page.waitForFunction(() => !document.querySelector('#excluir-comparacao').disabled);
  await page.locator('#excluir-comparacao').click();
  await page.locator('#confirmacao button[value="confirmar"]').click();
  await page.waitForFunction(() => document.querySelector('#total-comparacao').textContent === '0 envios nesta comparação');
  await formulario.close();
  await page.screenshot({path:'/tmp/rede-aberta-painel.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({path:'/tmp/rede-aberta-mobile.png',fullPage:true});
  await telao.setViewportSize({width:390,height:844});
  assert.equal(await telao.evaluate(() => document.querySelector('#palco').clientWidth),1920);
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button', {name:'Encerrar dinâmica', exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#status-rede').textContent === 'Parada');
  await page.locator('#excluir').click();
  await page.locator('#confirmacao button[value="confirmar"]').click();
  await page.waitForFunction(() => document.querySelector('#envios').textContent === '0');
  assert.deepEqual(erros, []);
  const requisicoes = await page.evaluate(async () => {
    const a = await fetch('/api/telao').then(r=>r.json());
    return {detalhes:'registros' in a, ativo:a.ativo};
  });
  assert.equal(requisicoes.detalhes,false);
  assert.equal(requisicoes.ativo,false);
  console.log('OK: navegação, ensaio, aparelho e envio simulados, popup, confirmação/cancelamento, revelação/ocultação, 7 slides sem sobreposição, tela móvel, HTTP/HTTPS reais pelo notebook, formulário do usuário, isolamento do cookie, projeção, encerramento e exclusão. Sem erros JavaScript.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
